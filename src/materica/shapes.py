class Case(TypedDict):
    """
    A conformance case file, one per arm of a case (README.md, "Case files").
    """

    case: str
    variant: NotRequired[str]
    suite: Suite
    schema_version: Version
    claims: NotRequired[dict[Suite, bool]]
    inputs: CaseInputs
    request: NotRequired[ReadRequest | CaseOperation | JsonValue]
    expected: ReadResult
    compare: CaseCompare


class ReadRequest(TypedDict):
    """
    read_side_contract.md section 1. A reader checks a request member by member at step 0, refusing with
    reasons, and ignores a member not named here, at any depth.
    """

    target: Target
    operating_conditions: NotRequired[dict[str, OperatingCondition]]
    requirement: Requirement
    acceptances: NotRequired[list[JsonObject]]


class ReadResult(TypedDict):
    """
    read_side_contract.md section 2.
    """

    status: ReadStatus
    reasons: list[Reason]
    value: NotRequired[JsonValue]
    alternative_values: NotRequired[list[JsonValue]]
    unit: NotRequired[JsonValue]
    conditions: NotRequired[list[JsonObject]]
    specimen: NotRequired[JsonObject]
    statistics: NotRequired[JsonObject]
    provenance: NotRequired[JsonObject]
    labels: NotRequired[list[str]]
    assumption: NotRequired[JsonObject]


class CaseOperation(TypedDict):
    """
    A case that is not a read (README.md, "Operations"), or a sampling case's draws mapped through a record's
    structure (README.md, "Case files"): the shape of each normal and uniform drawn, and of the result, are
    not yet specified.
    """

    operation: Literal["content_hash", "list_records", "transform_draws"]
    normals: NotRequired[list[JsonValue]]
    uniforms: NotRequired[list[JsonValue]]



"""Generate `schema/0.1/record.reader.json` from the writer schema beside it.

    python scripts/gen_reader_schema.py            # write the reader schema
    python scripts/gen_reader_schema.py --check    # fail if it differs from what the writer schema gives

The reader schema is the writer's, opened where `record_format.md` section 1 item 2 says a reader is open:
- every `$ref` is written out in place, except one to a shape the reader never applies (a value field, a
  section's `specimen`, an extension's contents), or to `json_value`, any value: those become `true`;
- an enumeration becomes any string, and `additionalProperties: false` and `propertyNames` go, so that members
  and tokens the reader does not know pass;
- a `pattern` stays only on the top-level `id`, `version` and `content_hash`, the three the item names.

Every pattern in the writer schema must start with `^` and end with `(?![\\s\\S])`: a validator's `$` also
matches before a final newline, so `"0.1.0\\n"` would match `^...$`.
"""

import json
import sys
from collections.abc import Sequence
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
SCHEMA = REPOSITORY / "src" / "materica" / "schema" / "0.1"
WRITER = SCHEMA / "record.writer.json"
READER = SCHEMA / "record.reader.json"
ID = "https://w3id.org/materica/schema/0.1/record.reader.json"
COMMENT = "Generated by scripts/gen_reader_schema.py from record.writer.json. Edit the writer schema."
DESCRIPTION = (
    "A record as a reader checks it at step 3 of a read (record_format.md section 1 item 2): the envelope, "
    "and the body's structure as far as schema 0.1 knows it. Open: members and tokens it does not know "
    "pass, and it never applies the shape of a value field, a form or a section's specimen."
)

NEVER_APPLIED = ("json_value", "value_field", "specimen", "extension")
PATTERNED = ("id", "version", "content_hash")
# The keywords whose value is a schema, or a list or map of schemas.
SUBSCHEMA = ("additionalProperties", "items", "not", "if", "then", "else")
SUBSCHEMAS = ("prefixItems", "allOf", "anyOf", "oneOf")

Json = bool | int | float | str | list["Json"] | dict[str, "Json"] | None


class SchemaError(ValueError):
    """A writer schema this script cannot open faithfully."""


def reader_schema(writer: dict[str, Json]) -> dict[str, Json]:
    definitions = writer["$defs"]
    if not isinstance(definitions, dict):
        raise SchemaError("$defs is not an object")

    def opened(node: Json, *, patterned: bool = False, root: bool = False) -> Json:
        if not isinstance(node, dict):
            return node
        if "$ref" in node:
            name = node["$ref"]
            if set(node) - {"$ref", "description"} or not isinstance(name, str):
                raise SchemaError(f"a $ref beside keywords other than description: {node}")
            name = name.removeprefix("#/$defs/")
            if name in NEVER_APPLIED:
                return True
            if name not in definitions:
                raise SchemaError(f"a $ref this script cannot follow: {node['$ref']}")
            return opened(definitions[name], patterned=patterned)
        reader: dict[str, Json] = {}
        for keyword, value in node.items():
            if keyword == "pattern":
                if not (isinstance(value, str) and value.startswith("^") and value.endswith("(?![\\s\\S])")):
                    raise SchemaError(f"a pattern that does not match in full: {value!r}")
                if patterned:
                    reader[keyword] = value
            elif keyword == "enum":
                if not (isinstance(value, list) and all(isinstance(token, str) for token in value)):
                    raise SchemaError(f"an enumeration of other than strings: {value!r}")
                reader["type"] = "string"
            elif keyword == "properties":
                if not isinstance(value, dict):
                    raise SchemaError(f"properties that are not an object: {value!r}")
                reader[keyword] = {
                    name: opened(member, patterned=root and name in PATTERNED)
                    for name, member in value.items()
                }
            elif keyword in SUBSCHEMA:
                reader[keyword] = opened(value)
            elif keyword in SUBSCHEMAS:
                if not isinstance(value, list):
                    raise SchemaError(f"{keyword} that is not a list: {value!r}")
                reader[keyword] = [opened(member) for member in value]
            elif keyword not in ("propertyNames", "$defs", "$comment"):
                reader[keyword] = value
        if reader.get("additionalProperties") in (False, True):
            del reader["additionalProperties"]
        return reader

    reader = opened(writer, root=True)
    assert isinstance(reader, dict)
    return {
        "$schema": reader.pop("$schema"),
        "$id": ID,
        "$comment": COMMENT,
        "title": reader.pop("title"),
        "description": DESCRIPTION,
        **{keyword: value for keyword, value in reader.items() if keyword not in ("$id", "description")},
    }


def generate(writer: Path = WRITER) -> str:
    schema: dict[str, Json] = json.loads(writer.read_text(encoding="utf-8"))
    return json.dumps(reader_schema(schema), indent=2) + "\n"


def main(arguments: Sequence[str] | None = None) -> int:
    arguments = sys.argv[1:] if arguments is None else arguments
    if list(arguments) not in ([], ["--check"]):
        print("usage: python scripts/gen_reader_schema.py [--check]", file=sys.stderr)
        return 2
    text = generate()
    if arguments:
        if not READER.is_file() or READER.read_text(encoding="utf-8") != text:
            print(
                f"{READER.name} differs from the writer schema: run scripts/gen_reader_schema.py",
                file=sys.stderr,
            )
            return 1
        return 0
    READER.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

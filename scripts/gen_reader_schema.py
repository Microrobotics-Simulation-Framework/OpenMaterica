"""Generate `schema/0.1/record.reader.json` from the writer schema beside it.

    python scripts/gen_reader_schema.py            # write the reader schema
    python scripts/gen_reader_schema.py --check    # fail if it differs from what the writer schema gives

The reader schema is the writer's, opened where `record_format.md` section 1 item 2 says a reader is open:
- every `$ref` is written out in place, except one to a shape the reader never applies (a value field, a
  section's `specimen`, an extension's contents), or to `json_value`, any value: those become `true`;
- an enumeration becomes any string, and `additionalProperties: false`, `unevaluatedProperties: false` and
  `propertyNames` go, so that members and tokens the reader does not know pass;
- a `pattern` stays only on the top-level `id`, `version` and `content_hash`, the three the item names.

Its `$defs` hold the shapes of a value field and a section's `specimen` as step 8 of a read checks them
(`read_side_contract.md` section 3), applied from nowhere in the schema, for a reader that checks one field
with them: opened in the same way, with their `$ref`s kept, a reference to the vocabulary's tokens or to an
identifier's pattern any string, no pattern, and every member marked `x-materica-write-only` any value and
required nowhere, since a read does not check it. A rule that reaches only such members, at any depth (an
`allOf` conjunct, or a condition's `then` and `else`), is the record checks' alone and is left out, and so is
a condition whose `if` tests one: a read cannot tell whether it holds. A conjunct, or a `then` and `else`,
that reaches members of both kinds stops the script.

An `allOf` conjunct that refers to one of the vocabulary's bindings (a section's field names and each field's
row, a numeric condition's unit, a specimen fact's fixed unit) is left out wherever it stands: those `$defs`
hold the shape of a value field whatever its name, and a read checks a field against its row in its own steps,
a unit at step 9 alone. A binding referred to anywhere else, or a vocabulary definition that is neither a
binding, a list of tokens nor an identifier's pattern, stops the script.

Every pattern in the writer schema must start with `^` and end with `(?![\\s\\S])`: a validator's `$` also
matches before a final newline, so `"0.1.0\\n"` would match `^...$`. Under `if` or `not`, anything the script
opens (an enumeration, a pattern, a closed object, `propertyNames`, a shape never applied, a member marked
write-only in either form), there or through a `$ref`, stops it, since opening it would turn the condition
around. So does a keyword the script does not know, whose subschemas it would copy unopened.

A member marked `{"unless": {<member>: <token>, ...}}` in place of `true` is one a read checks only where each
named member of its object, one a read checks, holds that token: a `derivation` for origin `derived`
(`provenance.md` section 2 item 6). Its shape, and whether its object requires it, are kept in a conjunct
under that condition; elsewhere it is as a member marked write-only. A rule in the `then` of a condition that
is exactly that one takes it as checked, and any other rule as unchecked.
"""

import json
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
SCHEMA = REPOSITORY / "src" / "materica" / "schema" / "0.1"
WRITER = SCHEMA / "record.writer.json"
READER = SCHEMA / "record.reader.json"
ID = "https://w3id.org/materica/schema/0.1/record.reader.json"
COMMENT = "Generated by scripts/gen_reader_schema.py from record.writer.json. Edit the writer schema."
DESCRIPTION = (
    "A record as a reader checks it at step 3 of a read (record_format.md section 1 item 2): the envelope, "
    "and the body's structure as far as schema 0.1 knows it. Open: members and tokens it does not know "
    "pass, and it never applies the shape of a value field, a form or a section's specimen. Its $defs hold "
    "those shapes as step 8 checks them (read_side_contract.md section 3), opened alike, without the members "
    "a read does not check."
)

NEVER_APPLIED = ("json_value", "value_field", "specimen", "extension")
CLOSING = ("additionalProperties", "unevaluatedProperties")
# The shapes the reader schema's `$defs` hold, with every definition they refer to.
CHECKED_AT_READ = ("value_field", "specimen")
WRITE_ONLY = "x-materica-write-only"
PATTERNED = ("id", "version", "content_hash")
# The keywords whose value is a schema, or a list or map of schemas.
SUBSCHEMA = (
    "additionalProperties",
    "unevaluatedProperties",
    "items",
    "contains",
    "not",
    "if",
    "then",
    "else",
)
SUBSCHEMAS = ("prefixItems", "allOf", "anyOf", "oneOf")
# The keywords copied as they are, which hold no subschema, and those the reader leaves out.
VERBATIM = (
    "type",
    "const",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "minItems",
    "maxItems",
    "uniqueItems",
    "title",
    "description",
    "$schema",
    "$id",
)
LEFT_OUT = ("propertyNames", "$defs", "$comment")
# Where the members a node marks write-only are required nowhere either: its conditions and alternatives.
SAME_OBJECT = ("then", "else", "allOf", "anyOf", "oneOf")
VOCABULARY_REF = re.compile(r"vocabulary/([a-z_]+\.json)#/\$defs/([a-z_]+)")

Json = bool | int | float | str | list["Json"] | dict[str, "Json"] | None


class SchemaError(ValueError):
    """A writer schema this script cannot open faithfully."""


@dataclass(frozen=True)
class Scope:
    """The object a subschema constrains: its members marked write-only, the definition each member refers
    to, its own and those the definitions its `allOf` refers to give it, and its members a read checks only
    under a condition not known to hold here, each with that condition."""

    write_only: frozenset[str]
    refers: dict[str, str]
    conditional: dict[str, Json] = field(default_factory=dict[str, Json])

    @property
    def unchecked(self) -> frozenset[str]:
        return self.write_only | frozenset(self.conditional)

    def where(self, condition: Json) -> "Scope":
        """This scope where `condition` holds: a member a read checks under exactly that condition is
        checked."""
        conditional = {name: kept for name, kept in self.conditional.items() if kept != condition}
        return Scope(self.write_only, self.refers, conditional)


UNSCOPED = Scope(frozenset(), {})
# The keywords that constrain the object a subschema applies to through another subschema.
SAME_OBJECT_RULES = ("allOf", "anyOf", "oneOf", "not", "if", "then", "else")


def reader_schema(writer: dict[str, Json], vocabulary: dict[str, Json] | None = None) -> dict[str, Json]:
    """The reader schema of `writer`, whose references to `vocabulary/<file>` resolve in `vocabulary`, by file
    name (schema 0.1's vocabulary where None)."""
    definitions = writer["$defs"]
    if not isinstance(definitions, dict):
        raise SchemaError("$defs is not an object")
    if vocabulary is None:
        vocabulary = {
            path.name: json.loads(path.read_text("utf-8")) for path in (SCHEMA / "vocabulary").glob("*.json")
        }
    needed: list[str] = []

    def opened(
        node: Json,
        *,
        inline: bool,
        patterned: bool = False,
        root: bool = False,
        outer: Scope = UNSCOPED,
    ) -> Json:
        """`node` opened; `inline` writes references out in place (the schema's root) or keeps them (its
        `$defs`); `outer` describes the object `node` constrains where `node` is a rule of an object outside
        it (a condition's result, a conjunct, a choice), whose members a read does not check here are
        required nowhere."""
        if not isinstance(node, dict):
            return node
        if "$ref" in node:
            return reference(node, inline=inline, patterned=patterned)
        inner = scope_of(node)
        scope = Scope(
            outer.write_only | inner.write_only,
            outer.refers | inner.refers,
            outer.conditional | inner.conditional,
        )
        read_where = members_read_where(node)
        own = outer.unchecked | members_marked(node) | frozenset(read_where)
        node = without_record_checks(node, scope)
        reader: dict[str, Json] = {}
        for keyword, value in node.items():
            if keyword == "pattern":
                if not (isinstance(value, str) and value.startswith("^") and value.endswith("(?![\\s\\S])")):
                    raise SchemaError(f"a pattern that does not match in full: {value!r}")
                if patterned:
                    reader[keyword] = value
            elif keyword == "enum":
                if not (isinstance(value, list) and all(isinstance(token, str) for token in value)):
                    raise SchemaError(f"an enumeration of other than strings: {value!r}")
                reader["type"] = "string"
            elif keyword == "required":
                if not (isinstance(value, list) and all(isinstance(name, str) for name in value)):
                    raise SchemaError(f"required that is not a list of names: {value!r}")
                if kept := [name for name in value if name not in own]:
                    reader[keyword] = kept
            elif keyword == "properties":
                if not isinstance(value, dict):
                    raise SchemaError(f"properties that are not an object: {value!r}")
                reader[keyword] = {
                    name: True
                    if name in own
                    else opened(member, inline=inline, patterned=root and name in PATTERNED)
                    for name, member in value.items()
                }
            elif keyword in SUBSCHEMA:
                if keyword in ("if", "not") and opens(value, set()):
                    raise SchemaError(
                        f"{keyword} holds what the reader opens, which would turn it around: {value}"
                    )
                within = scope if keyword in SAME_OBJECT else UNSCOPED
                if keyword == "then":
                    within = scope.where(node.get("if"))
                reader[keyword] = opened(value, inline=inline, outer=within)
            elif keyword in SUBSCHEMAS:
                if not isinstance(value, list):
                    raise SchemaError(f"{keyword} that is not a list: {value!r}")
                within = scope if keyword in SAME_OBJECT else UNSCOPED
                applied = [member for member in value if not (keyword == "allOf" and binding(member))]
                reader[keyword] = [opened(member, inline=inline, outer=within) for member in applied]
            elif keyword == WRITE_ONLY:
                raise SchemaError(f"{WRITE_ONLY} marks a member of properties, and nothing else: {node}")
            elif keyword in VERBATIM:
                reader[keyword] = value
            elif keyword not in LEFT_OUT:
                raise SchemaError(f"a keyword this script does not know: {keyword}")
        if checked_where := conditional_checks(node, read_where, inline=inline):
            reader["allOf"] = [*as_list(reader.get("allOf")), *checked_where]
        return without_empty(reader)

    def conditional_checks(node: dict[str, Json], read_where: dict[str, Json], *, inline: bool) -> list[Json]:
        """For each member of `node` a read checks only under a condition, a conjunct that applies its shape
        where the condition holds, and requires it there where `node` requires it."""
        required = names_in(node.get("required"))
        members = as_object(node.get("properties"))
        conjuncts: list[Json] = []
        for name, condition in read_where.items():
            shape = {
                keyword: value for keyword, value in as_object(members[name]).items() if keyword != WRITE_ONLY
            }
            then: dict[str, Json] = {"properties": {name: opened(shape, inline=inline)}}
            if name in required:
                then["required"] = [name]
            conjuncts.append({"if": condition, "then": then})
        return conjuncts

    def scope_of(node: dict[str, Json]) -> Scope:
        marked = set(members_marked(node))
        conditional = members_read_where(node)
        refers: dict[str, str] = {}
        for conjunct in as_list(node.get("allOf")):
            if (base := local(conjunct)) in definitions:
                inherited = scope_of(as_object(definitions[base]))
                marked |= inherited.write_only
                conditional |= inherited.conditional
                refers |= inherited.refers
        for name, member in as_object(node.get("properties")).items():
            if (target := local(member)) in definitions:
                refers[name] = target
        return Scope(frozenset(marked), refers, conditional)

    def reached(rule: Json, scope: Scope, *, conditions: bool = True) -> set[bool]:
        """For each member `rule` requires or constrains, at any depth, of the object `scope` describes,
        whether a read leaves it unchecked: True where its path passes a member marked write-only, or one a
        read checks under a condition not known to hold there. Without `conditions`, a condition of `rule`
        itself is left out, which `opened` judges on its own."""
        rule = as_object(rule)
        found = {name in scope.unchecked for name in names_in(rule.get("required"))}
        for name, member in as_object(rule.get("properties")).items():
            if name in scope.unchecked:
                found.add(True)
                continue
            if set(as_object(member)) - set(SAME_OBJECT_RULES) - {"properties", "required"}:
                found.add(False)
            nested = (
                scope_of(as_object(definitions[scope.refers[name]])) if name in scope.refers else UNSCOPED
            )
            found |= reached(member, nested)
        for keyword in SAME_OBJECT_RULES:
            if keyword in rule and (conditions or keyword not in ("if", "then", "else")):
                value = rule[keyword]
                within = scope.where(rule.get("if")) if keyword == "then" else scope
                for part in as_list(value) if isinstance(value, list) else [value]:
                    found |= reached(part, within)
        return found

    def without_record_checks(node: dict[str, Json], scope: Scope) -> dict[str, Json]:
        """`node` without its rules a read cannot apply: an `allOf` conjunct that reaches only members a
        read does not check, and a condition whose `if` tests one or whose `then` and `else` reach only
        such members."""
        kept = dict(node)
        if "if" in node:
            tested = reached(node["if"], scope)
            results = reached(node.get("then"), scope.where(node["if"])) | reached(node.get("else"), scope)
            if results == {True, False} and True not in tested:
                raise SchemaError(f"a then or else that reaches members a read checks and others: {node}")
            if True in tested or results == {True}:
                for keyword in ("if", "then", "else"):
                    kept.pop(keyword, None)
        conjuncts = node.get("allOf")
        if isinstance(conjuncts, list):
            unchecked = [reached(conjunct, scope, conditions=False) for conjunct in conjuncts]
            if any(found == {True, False} for found in unchecked):
                raise SchemaError(f"an allOf conjunct that reaches members a read checks and others: {node}")
            kept["allOf"] = [
                conjunct for conjunct, found in zip(conjuncts, unchecked, strict=True) if found != {True}
            ]
        return kept

    def opens(node: Json, seen: set[str]) -> bool:
        """Whether opening `node` changes what it accepts: whether it holds, or reaches through a `$ref`, an
        enumeration, a pattern, a closed object, `propertyNames`, a shape never applied or a member marked
        write-only in either form."""
        if isinstance(node, list):
            return any(opens(item, seen) for item in node)
        if not isinstance(node, dict):
            return False
        if isinstance(target := node.get("$ref"), str):
            name = target.removeprefix("#/$defs/")
            if VOCABULARY_REF.fullmatch(target) or (name in NEVER_APPLIED and name != "json_value"):
                return True
            if name in seen or name not in definitions:
                return False
            return opens(definitions[name], seen | {name})
        closed = any(node.get(keyword, True) is not True for keyword in CLOSING)
        if closed or {"enum", "pattern", "propertyNames"} & set(node) or marks(node):
            return True
        return any(opens(value, seen) for keyword, value in node.items() if keyword != "$defs")

    def binding(node: Json) -> bool:
        """Whether `node` is a reference to one of the vocabulary's bindings."""
        target = as_object(node).get("$ref")
        found = VOCABULARY_REF.fullmatch(target) if isinstance(target, str) else None
        return found is not None and binds(vocabulary, found[1], found[2])

    def reference(node: dict[str, Json], *, inline: bool, patterned: bool) -> Json:
        target = node["$ref"]
        if set(node) - {"$ref", "description"} or not isinstance(target, str):
            raise SchemaError(f"a $ref beside keywords other than description: {node}")
        if vocabulary_ref := VOCABULARY_REF.fullmatch(target):
            if binding(node):
                raise SchemaError(f"a vocabulary binding applied other than as an allOf conjunct: {target}")
            if not (
                enumerates(vocabulary, vocabulary_ref[1], vocabulary_ref[2])
                or patterns(vocabulary, vocabulary_ref[1], vocabulary_ref[2])
            ):
                raise SchemaError(f"a $ref to the vocabulary that is no list of tokens or pattern: {target}")
            return {"type": "string"}
        name = target.removeprefix("#/$defs/")
        if name == "json_value" or (inline and name in NEVER_APPLIED):
            return True
        if name not in definitions or not target.startswith("#/$defs/"):
            raise SchemaError(f"a $ref this script cannot follow: {target}")
        if inline:
            return opened(definitions[name], inline=True, patterned=patterned)
        if name not in needed:
            needed.append(name)
        return {keyword: node[keyword] for keyword in ("description", "$ref") if keyword in node}

    reader = opened(writer, inline=True, root=True)
    assert isinstance(reader, dict)
    if absent := [name for name in CHECKED_AT_READ if name not in definitions]:
        raise SchemaError(f"no definition of the shapes a read checks: {absent}")
    needed.extend(CHECKED_AT_READ)
    shapes: dict[str, Json] = {}
    while missing := [name for name in needed if name not in shapes]:
        for name in missing:
            shapes[name] = opened(definitions[name], inline=False)
    return {
        "$schema": reader.pop("$schema"),
        "$id": ID,
        "$comment": COMMENT,
        "title": reader.pop("title"),
        "description": DESCRIPTION,
        **{keyword: value for keyword, value in reader.items() if keyword not in ("$id", "description")},
        "$defs": {name: shapes[name] for name in definitions if name in shapes},
    }


def local(subschema: Json) -> str | None:
    """The definition a subschema's local `$ref` names, or None."""
    target = as_object(subschema).get("$ref")
    return (
        target.removeprefix("#/$defs/") if isinstance(target, str) and target.startswith("#/$defs/") else None
    )


def as_object(value: Json) -> dict[str, Json]:
    return value if isinstance(value, dict) else {}


def as_list(value: Json) -> list[Json]:
    return value if isinstance(value, list) else []


def names_in(value: Json) -> list[str]:
    return [name for name in value if isinstance(name, str)] if isinstance(value, list) else []


def members_marked(node: dict[str, Json]) -> frozenset[str]:
    """The members of `node`'s properties marked write-only, `true`."""
    return frozenset(name for name, condition in marks(node).items() if condition is None)


def members_read_where(node: dict[str, Json]) -> dict[str, Json]:
    """The members of `node`'s properties a read checks only under a condition, each with the condition as
    the `if` of a schema of `node`'s object."""
    return {name: condition for name, condition in marks(node).items() if condition is not None}


def marks(node: dict[str, Json]) -> dict[str, Json]:
    """Each member of `node`'s properties marked write-only: None where the mark is `true`, and the condition
    under which a read checks it where it is `{"unless": {<member>: <token>, ...}}`, each member named one of
    `node`'s properties that no mark makes unchecked."""
    members = as_object(node.get("properties"))
    found: dict[str, Json] = {}
    for name, member in members.items():
        if WRITE_ONLY not in as_object(member):
            continue
        mark = as_object(member)[WRITE_ONLY]
        if mark is True:
            found[name] = None
            continue
        tokens = as_object(mark).get("unless") if set(as_object(mark)) == {"unless"} else None
        if not (
            isinstance(tokens, dict) and tokens and all(isinstance(token, str) for token in tokens.values())
        ):
            raise SchemaError(f"{WRITE_ONLY} on {name} neither true nor unless members hold tokens: {mark}")
        if unread := [
            tested for tested in tokens if tested not in members or WRITE_ONLY in as_object(members[tested])
        ]:
            raise SchemaError(
                f"{name} checked at read under a condition on {unread}, which a read does not check"
            )
        required: list[Json] = [*tokens]
        constants: dict[str, Json] = {tested: {"const": token} for tested, token in tokens.items()}
        found[name] = {"required": required, "properties": constants}
    return found


def enumerates(vocabulary: dict[str, Json], name: str, definition: str) -> bool:
    """Whether the vocabulary file `name` defines `definition` as an enumeration of strings, and only that."""
    contents = vocabulary.get(name)
    definitions = contents.get("$defs") if isinstance(contents, dict) else None
    found = definitions.get(definition) if isinstance(definitions, dict) else None
    tokens = found.get("enum") if isinstance(found, dict) and set(found) == {"enum"} else None
    return isinstance(tokens, list) and all(isinstance(token, str) for token in tokens)


def patterns(vocabulary: dict[str, Json], name: str, definition: str) -> bool:
    """Whether the vocabulary file `name` defines `definition` as a string of a pattern that matches in full,
    and only that: an identifier's form (`"UBERON:<digits>"`), which a read does not check."""
    contents = vocabulary.get(name)
    definitions = contents.get("$defs") if isinstance(contents, dict) else None
    found = definitions.get(definition) if isinstance(definitions, dict) else None
    pattern = found.get("pattern") if isinstance(found, dict) and set(found) == {"type", "pattern"} else None
    return (
        isinstance(found, dict)
        and found.get("type") == "string"
        and isinstance(pattern, str)
        and pattern.startswith("^")
        and pattern.endswith("(?![\\s\\S])")
    )


def binds(vocabulary: dict[str, Json], name: str, definition: str) -> bool:
    """Whether the vocabulary file `name` defines `definition` as a binding: a schema of the members a name's
    row fixes (`properties`, `propertyNames`), holding no list of tokens of its own."""
    contents = vocabulary.get(name)
    definitions = contents.get("$defs") if isinstance(contents, dict) else None
    found = definitions.get(definition) if isinstance(definitions, dict) else None
    structure = {"properties", "propertyNames"}
    return isinstance(found, dict) and "enum" not in found and bool(structure & set(found))


def without_empty(reader: dict[str, Json]) -> dict[str, Json]:
    """`reader` without what checks nothing once opened: an open `additionalProperties` or
    `unevaluatedProperties`, an `if` whose `then` and `else` check nothing, and an empty `allOf` member."""
    for keyword in ("additionalProperties", "unevaluatedProperties"):
        if reader.get(keyword) in (False, True):
            del reader[keyword]
    if "if" in reader and reader.get("then", {}) in ({}, True) and reader.get("else", {}) in ({}, True):
        for keyword in ("if", "then", "else"):
            reader.pop(keyword, None)
    if isinstance(conjuncts := reader.get("allOf"), list):
        if kept := [conjunct for conjunct in conjuncts if conjunct not in ({}, True)]:
            reader["allOf"] = kept
        else:
            del reader["allOf"]
    return reader


def generate(writer: Path = WRITER) -> str:
    schema: dict[str, Json] = json.loads(writer.read_text(encoding="utf-8"))
    return json.dumps(reader_schema(schema), indent=2) + "\n"


def main(arguments: Sequence[str] | None = None) -> int:
    arguments = sys.argv[1:] if arguments is None else arguments
    if list(arguments) not in ([], ["--check"]):
        print("usage: python scripts/gen_reader_schema.py [--check]", file=sys.stderr)
        return 2
    text = generate()
    if arguments:
        if not READER.is_file() or READER.read_text(encoding="utf-8") != text:
            print(
                f"{READER.name} differs from the writer schema: run scripts/gen_reader_schema.py",
                file=sys.stderr,
            )
            return 1
        return 0
    READER.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

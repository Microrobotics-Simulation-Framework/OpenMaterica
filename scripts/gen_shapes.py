"""Generate `src/materica/shapes.py` and `shapes.pyi`, the JSON shapes as TypedDicts, from the schemas.

    python scripts/gen_shapes.py            # write both files
    python scripts/gen_shapes.py --check    # fail if either differs from what the schemas give

The shapes come from `schema/0.1/record.writer.json`, `case.json` with the read request it refers to,
`read_result.json`, which a case's expected answer no longer names whole, since it may leave members out,
`declaration.json` and `build_report.json`, through datamodel-code-generator, pinned in the dev group, then
ruff. A member the schemas declare `integer` is typed `float`, since the reader gives every JSON number as a
double (`record_format.md` section 1 item 6): a whole number is a `float` with no fractional part, so a
consumer type-checks against what it is given. The vocabulary's bindings, which the writer schema applies by
`allOf` to bind a name to its row (a section's field names, a field's forms, unit and label, a numeric
condition's unit), are left out: a TypedDict cannot narrow a member by the name it sits under, and the shapes
stay those of a value field whatever its name. So are declaration.json's rules and bindings (`*_rule`,
`*_binding`), and the read request's acceptance shapes it applies by `allOf`, whose members its own
definitions type; and `unevaluatedProperties`, which closes a definition whose members come through a `$ref`,
since a TypedDict states no closure. `shapes.py` uses the standard
library only, so the package keeps no run-time dependency; `shapes.pyi`, which type checkers read in its
place, adds PEP 705's `ReadOnly` to every member of the shapes a read or a build returns, from
`typing_extensions`, which
type checkers resolve from their own typeshed. datamodel-code-generator 0.83 does not run on Python 3.15: run
this script with 3.11 to 3.14.
"""

import json
import re
import shutil
import subprocess
import sys
import tempfile
import textwrap
from collections.abc import Sequence
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
PACKAGE = REPOSITORY / "src" / "materica"
SHAPES = PACKAGE / "shapes.py"
STUB = PACKAGE / "shapes.pyi"

# What a read or a build returns: frozen dataclasses give these through `to_json`, and a consumer never writes
# into them.
READ_ONLY = (
    "ReadResult",
    "Reason",
    "BuildReport",
    "BuildRefusalJson",
    "BuildResultJson",
    "CombinationResultJson",
    "SpecimenDifference",
    "UnusedAcceptance",
    "Watch",
)

HEADER = '''# SPDX-License-Identifier: Apache-2.0
"""The JSON shapes of records, read requests, read results, case files, declarations and build reports, as
TypedDicts.

Generated by scripts/gen_shapes.py from the schemas in schema/0.1/: edit the schemas. A shape describes; it
never validates. The reader checks what it is given at run time, whatever its type. Every number is a float,
as the reader gives it, a count or an index included: a whole number is a float with no fractional part.
"""'''


def generated_text() -> str:
    """datamodel-code-generator's module, from a root that names the schemas, in a temporary copy of them, so
    that their relative references resolve as files, never over a network, and nothing is written into the
    package."""
    from datamodel_code_generator import InputFileType, PythonVersion, generate
    from datamodel_code_generator.enums import DataModelType

    with tempfile.TemporaryDirectory() as directory:
        copy = Path(directory)
        shutil.copytree(PACKAGE / "schema", copy / "schema")
        for schema in (copy / "schema").rglob("*.json"):
            contents = as_read(json.loads(schema.read_text("utf-8")))
            if schema.parent.name == "vocabulary":
                contents = without_bindings(contents)
            else:
                contents = without_rules(contents)
            schema.write_text(json.dumps(contents), encoding="utf-8")
        root = copy / "shapes_root.json"
        root.write_text(
            json.dumps(
                {
                    "$schema": "https://json-schema.org/draft/2020-12/schema",
                    "anyOf": [
                        {"$ref": "schema/0.1/record.writer.json"},
                        {"$ref": "schema/0.1/case.json"},
                        {"$ref": "schema/0.1/read_result.json"},
                        {"$ref": "schema/0.1/declaration.json"},
                        {"$ref": "schema/0.1/build_report.json"},
                    ],
                }
            ),
            encoding="utf-8",
        )
        text = generate(
            root,
            input_file_type=InputFileType.JsonSchema,
            output_model_type=DataModelType.TypingTypedDict,
            target_python_version=PythonVersion.PY_311,
            class_name="Shapes",
            use_title_as_name=True,
            use_standard_collections=True,
            use_union_operator=True,
            use_type_alias=True,
            use_closed_typed_dict=False,
            use_schema_description=True,
            treat_dot_as_module=False,
            allow_remote_refs=False,
            disable_timestamp=True,
            formatters=[],
        )
    if not isinstance(text, str):
        raise TypeError("datamodel-code-generator gave several modules, not one")
    # The root is only the union of the two schemas' roots, and is no shape.
    text, removed = re.subn(r"\nShapes: TypeAlias = [^\n]*\n", "\n", text)
    if removed != 1 or not text.startswith("# generated by datamodel-codegen:\n"):
        raise ValueError("not the module this script expects: has datamodel-code-generator changed?")
    return HEADER + wrapped(functional_last(text.split("\n", 2)[2]))


Json = bool | int | float | str | list["Json"] | dict[str, "Json"] | None


def as_read(node: Json) -> Json:
    """`node` with every `integer` type a `number`, since the reader gives a whole number as a double, and
    without the `allOf` conjuncts that refer to the vocabulary, which bind names to their rows."""
    if isinstance(node, list):
        return [as_read(item) for item in node]
    if not isinstance(node, dict):
        return node
    found: dict[str, Json] = {}
    for keyword, value in node.items():
        if keyword == "type" and value == "integer":
            found[keyword] = "number"
        elif keyword == "unevaluatedProperties":
            continue
        elif keyword == "allOf" and isinstance(value, list):
            if kept := [as_read(conjunct) for conjunct in value if not binding(conjunct)]:
                found[keyword] = kept
        else:
            found[keyword] = as_read(value)
    return found


def binding(conjunct: Json) -> bool:
    """Whether an `allOf` conjunct only narrows members its schema types itself: a vocabulary binding; one of
    declaration.json's rules and bindings (`*_rule`, `*_binding`); or the read request's shape of an
    acceptance, whose members the declaration's own definition repeats."""
    target = conjunct.get("$ref") if isinstance(conjunct, dict) else None
    if not isinstance(target, str):
        return False
    local = target.removeprefix("#/$defs/")
    return target.startswith(("vocabulary/", "read_request.json#")) or (
        local != target and _RULE.fullmatch(local) is not None
    )


def without_bindings(vocabulary: Json) -> Json:
    """A vocabulary file without its bindings, the definitions that are schemas of members rather than lists
    of tokens, which datamodel-code-generator would otherwise type as shapes of their own."""
    if not isinstance(vocabulary, dict) or not isinstance(definitions := vocabulary.get("$defs"), dict):
        return vocabulary
    kept = {
        name: definition
        for name, definition in definitions.items()
        if not (isinstance(definition, dict) and {"properties", "propertyNames"} & set(definition))
    }
    return {**vocabulary, "$defs": kept}


_RULE = re.compile(r"\w+_(?:rule|binding)")


def without_rules(schema: Json) -> Json:
    """A schema without its definitions named `*_rule` or `*_binding` (declaration.json's), which `as_read`
    has left unreferenced: each only narrows members typed elsewhere, and refers to bindings the vocabulary's
    copy no longer holds."""
    if not isinstance(schema, dict) or not isinstance(definitions := schema.get("$defs"), dict):
        return schema
    kept = {name: definition for name, definition in definitions.items() if not _RULE.fullmatch(name)}
    return {**schema, "$defs": kept}


_FUNCTIONAL = re.compile(r"\n(\w+) = TypedDict\('\1', \{\n.*?\}\)\n", re.S)


def functional_last(text: str) -> str:
    """`text` with each TypedDict written in the functional form, as one with a member named by a Python
    keyword (`import`) is, moved to its end and its references to itself quoted: unlike a class's
    annotations, its members are evaluated when the module is imported, so every name they use must be
    defined by then."""
    found = list(_FUNCTIONAL.finditer(text))
    for match in found:
        text = text.replace(match[0], "\n")
    for match in found:
        head, brace, members = match[0].partition("{")
        text += head + brace + re.sub(rf"\b{match[1]}\b", f"'{match[1]}'", members)
    return text


def wrapped(text: str) -> str:
    """`text` with each docstring line longer than the repository's 110 columns wrapped."""
    lines: list[str] = []
    in_docstring = False
    for line in text.splitlines():
        if line.strip() == '"""':
            in_docstring = not in_docstring
        elif in_docstring and len(line) > 110:
            indent = line[: len(line) - len(line.lstrip())]
            lines += textwrap.wrap(line.strip(), 110, initial_indent=indent, subsequent_indent=indent)
            continue
        lines.append(line)
    return "\n".join(lines) + "\n"


def ruff(text: str, path: Path) -> str:
    for command in (["check", "--fix", "--exit-zero", "--quiet"], ["format"]):
        text = subprocess.run(
            [sys.executable, "-m", "ruff", *command, "--stdin-filename", str(path), "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
            cwd=REPOSITORY,
        ).stdout
    return text


def read_only(text: str) -> str:
    """`text` with every member of the READ_ONLY shapes wrapped in `ReadOnly`."""
    lines = text.splitlines()
    shape = None
    for index, line in enumerate(lines):
        if line.startswith("class "):
            shape = line.removeprefix("class ").partition("(")[0]
        elif line and not line.startswith(" "):
            shape = None
        elif shape in READ_ONLY and (member := re.fullmatch(r"    (\w+): (.+)", line)):
            lines[index] = f"    {member[1]}: ReadOnly[{member[2]}]"
    text = "\n".join(lines) + "\n"
    return text.replace(
        "\nfrom typing import", "\nfrom typing_extensions import ReadOnly\nfrom typing import", 1
    )


def generate() -> dict[Path, str]:
    shapes = ruff(generated_text(), SHAPES)
    return {SHAPES: shapes, STUB: ruff(read_only(shapes), STUB)}


def main(arguments: Sequence[str] | None = None) -> int:
    arguments = sys.argv[1:] if arguments is None else arguments
    if list(arguments) not in ([], ["--check"]):
        print("usage: python scripts/gen_shapes.py [--check]", file=sys.stderr)
        return 2
    files = generate()
    if arguments:
        differing = [
            path for path, text in files.items() if not path.is_file() or path.read_text("utf-8") != text
        ]
        for path in differing:
            print(f"{path.name} differs from the schemas: run scripts/gen_shapes.py", file=sys.stderr)
        return 1 if differing else 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
